    private void btnAbrirArchivoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirArchivoActionPerformed
        fileChooser.setSelectedFile(null);
        int resultado = fileChooser.showOpenDialog(null);
        if (resultado == JFileChooser.APPROVE_OPTION) {
            File archivo = fileChooser.getSelectedFile();
            try {
                RespuestaArchivo respuesta = controlador.cargarArchivo(archivo);
                if (respuesta.isValido()) {
                    PanelEscritor escritor = new PanelEscritor(this, controlador, archivo, respuesta.getLineas(), respuesta.getMensaje());
                    espacio.add(escritor);
                } else {
                    mostrarMensaje(respuesta.getMensaje());
                }
            } catch (ErrorDeArchivoException e) {
                mostrarMensaje(e.getMessage());
            }
        }
    }//GEN-LAST:event_btnAbrirArchivoActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        fileChooser.setSelectedFile(null);
        int resultado = fileChooser.showSaveDialog(null);
        if (resultado == JFileChooser.APPROVE_OPTION) {
            try {
                File file = fileChooser.getSelectedFile();
                File archivo = controlador.crearArchivo(file);
                PanelEscritor escritor = new PanelEscritor(this, controlador, archivo, 0, "");
                espacio.add(escritor);
            } catch (ErrorDeArchivoException e) {
                mostrarMensaje(e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

