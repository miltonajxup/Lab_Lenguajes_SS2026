    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            controlador.guardarCambios(archivo, entorno.getText());
        } catch (ErrorDeArchivoException e) {
            mostrarMensaje(e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnCompilarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompilarActionPerformed
        try {
            String[] opciones = controlador.getFormatosGuardado();
            int eleccion = JOptionPane.showOptionDialog(this, "Elige la opcion de Guardado del Promt", "Formato", JOptionPane.DEFAULT_OPTION, JOptionPane.QUESTION_MESSAGE, null, opciones, opciones[0]);
            
            ResultadoAnalisis resultado = controlador.analizarArchivo(archivo, entorno.getText(), eleccion);
            ide.agregarResultados(resultado);
        } catch (ErrorDeArchivoException | ValorInvalidoException e) {
            mostrarMensaje(e.getMessage());
        }
    }//GEN-LAST:event_btnCompilarActionPerformed


