    public PanelEscritor(IDEPromt ide, ControladorDeArchivo controlador, File archivo, int cantidadFilas, String texto) {
        initComponents();
        this.ide = ide;
        this.controlador = controlador;
        this.archivo = archivo;
        String nombre = archivo.getName();
        this.setName(nombre);
        filas.setEditable(false);
        filas.setFont(new Font("Liberarion Sans", 0, 22));
        entorno.setFont(new Font("Liberarion Sans", 0, 22));
        entorno.setText(texto);
        columna = 1;
        for (int i = 0; i < cantidadFilas - 1; i++) {
            agregarColumna();
        }
        jScrollPane2.setRowHeaderView(filas);
        entorno.addKeyListener(new KeyAdapter() {
            @Override
            public void keyPressed(KeyEvent e) {
                if (e.getKeyCode() == KeyEvent.VK_ENTER) {
                    agregarColumna();
                }
            }
        });
        this.remove(espacioTabla2);
    }
    
